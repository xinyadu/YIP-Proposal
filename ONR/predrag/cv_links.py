"""Restore the CV's links inside main-full.pdf.

\\includepdf (pdfpages) keeps the look of cv_onr.pdf but drops its links
(Google Scholar, DBLP, homepage, paper links, and jumps to numbered papers).
This script reads the links from cv_onr.pdf and writes cv_links.tex, which
places an invisible link of the same size at the same spot on each page.
main-full.tex inputs cv_links.tex if it exists.

Run it again whenever cv_onr.pdf changes:
    python3 cv_links.py            (needs: pip install pypdf)
"""
import pypdf

SRC, OUT = 'cv_onr.pdf', 'cv_links.tex'


def esc(url):
    # characters that are special inside a macro argument
    for a, b in (('\\', '/'), ('%', '\\%'), ('#', '\\#'), ('&', '\\&'), ('~', '\\~'), ('_', '\\_')):
        url = url.replace(a, b)
    return url


r = pypdf.PdfReader(SRC)
pages = {i + 1: [] for i in range(len(r.pages))}
used = set()
for i, pg in enumerate(r.pages):
    for a in pg.get('/Annots') or []:
        a = a.get_object()
        act = a.get('/A')
        if a.get('/Subtype') != '/Link' or act is None:
            continue
        act = act.get_object()
        x1, y1, x2, y2 = (float(v) for v in a['/Rect'])
        box = f'\\put({x1:.1f},{y1:.1f}){{%s{{\\makebox({x2 - x1:.1f},{y2 - y1:.1f}){{}}}}}}'
        if act.get('/S') == '/URI':
            pages[i + 1].append(box % f'\\href{{{esc(str(act["/URI"]))}}}')
        elif act.get('/S') == '/GoTo' and isinstance(act.get('/D'), str):
            name = str(act['/D'])
            used.add(name)
            pages[i + 1].append(box % f'\\hyperlink{{cv-{name}}}')

nd = r.named_destinations
for name in sorted(used):
    if name in nd:
        d = nd[name]
        p = r.get_destination_page_number(d) + 1
        x = float(d.get('/Left') or 0)
        y = float(d.get('/Top') or 0)
        pages[p].append(f'\\put({x:.1f},{y:.1f}){{\\hypertarget{{cv-{name}}}{{}}}}')

with open(OUT, 'w') as f:
    f.write('% Generated by cv_links.py from cv_onr.pdf; do not edit by hand.\n')
    f.write('% Invisible links placed over the included CV pages (coordinates in bp).\n')
    for p, items in pages.items():
        f.write(f'\\expandafter\\def\\csname cvlinks@p{p}\\endcsname{{%\n')
        for it in items:
            f.write(it + '%\n')
        f.write('}\n')
print(f'wrote {OUT}: {sum(len(v) for v in pages.values())} items on {len(pages)} pages')
